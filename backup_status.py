"""Snapshot experiment state for backup/recovery (read-only w.r.t. experiments).

Writes reports/run_status.md, reports/run_status.json, and copies process logs into
logs/process_logs/ plus per-run log excerpts into logs/experiments/<run_id>/ (originals untouched).
Usage: PYTHONPATH=src python scripts/backup_status.py
"""
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from mobiphysio import pipeline as P  # noqa: E402

TS = re.compile(r"^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})")


def main():
    ctx = P.Context.create(None, "experiment", {})
    data = ctx.data_dir
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    # 1. copy raw process logs (never move/overwrite originals)
    pl = ROOT / "logs" / "process_logs"
    pl.mkdir(parents=True, exist_ok=True)
    logs = sorted(data.glob("*.log")) + sorted(data.glob("*.sh"))
    for f in logs:
        shutil.copy2(f, pl / f.name)
    shutil.copy2(ROOT / "results" / "logs" / "execution.log", pl / "execution.log") if (ROOT / "results/logs/execution.log").exists() else None
    lines = []
    for f in sorted(pl.glob("*.log")):
        for ln in f.read_text(errors="replace").splitlines():
            m = TS.match(ln)
            if m:
                lines.append((m.group(1), f.name, ln))
    # 2. live processes
    ps = subprocess.run(["ps", "-eo", "pid,lstart,etime,args"], capture_output=True, text=True).stdout
    active = [ln for ln in ps.splitlines() if "mobiphysio.cli" in ln and "grep" not in ln]
    # 3. runs
    reg = json.loads((ctx.run_root / "registry.json").read_text())
    registered = {Path(v).name for seeds in reg["seeds"].values() for v in seeds.values()}
    rows = []
    for m in sorted(ctx.run_root.glob("*/*/run_manifest.json")):
        j = json.loads(m.read_text())
        rid, st = j["run_id"], j["exit_status"]
        ck = (j.get("outputs") or {}).get("checkpoint")
        met = {}
        if (m.parent / "metrics.json").exists():
            mm = json.loads((m.parent / "metrics.json").read_text())
            met = {"macro_f1": mm.get("macro_f1"), "accuracy": mm.get("accuracy")}
        # last epoch seen in logs between start and (end or now)
        start = j["started_utc"].replace("T", " ").rstrip("Z")
        end = (j.get("ended_utc") or now).replace("T", " ").rstrip("Z")
        mine = [ln for t, _, ln in lines if start <= t <= end]
        ep = [int(x) for x in re.findall(r"epoch (\d+) loss", "\n".join(mine))]

        d = ROOT / "logs" / "experiments" / rid
        d.mkdir(parents=True, exist_ok=True)
        (d / "log_excerpt.log").write_text("\n".join(mine) + "\n")
        for fn in ["run_manifest.json", "history.json", "metrics.json"]:
            if (m.parent / fn).exists():
                shutil.copy2(m.parent / fn, d / fn)
        if st == "running" and not any(rid.split("-")[0] in a for a in active):
            st = "running (no live process found)"
        rows.append({"run_id": rid, "model": j["model"], "seed": j["seed"], "status": st,
                     "registered": rid in registered, "started_utc": j["started_utc"], "ended_utc": j.get("ended_utc"),
                     "last_epoch_in_logs": max(ep) if ep else None, "best_epoch": j.get("best_epoch"),
                     "best_val_macro_f1": j.get("best_val_macro_f1"), "checkpoint": ck["path"] if ck else None,
                     "checkpoint_sha256": ck["sha256"] if ck else None, **met,
                     "run_dir": str(m.parent.relative_to(ROOT)), "log_excerpt": str((d / "log_excerpt.log").relative_to(ROOT))})
    # 4. planned matrix: final + ablations + historical, all seeds
    seeds = [ctx.exp_cfg["seed"]] + list(ctx.exp_cfg["evaluation"].get("extra_training_seeds", []))
    planned = []
    for k in P.final_models(ctx) + P.ablation_keys(ctx) + P.historical_models(ctx):
        for s in seeds:
            done = str(s) in reg["seeds"].get(k, {})
            live = [r for r in rows if r["model"] == k and r["seed"] == s and r["status"].startswith("running")]
            planned.append({"model": k, "seed": s, "status": "completed" if done else ("running" if live else "pending"),
                            "historical": k in P.historical_models(ctx)})
    out = {"generated_utc": now, "active_processes": active, "planned": planned, "runs": rows}
    (ROOT / "reports" / "run_status.json").write_text(json.dumps(out, indent=1))
    resume = "cd MobiPhysio-Net && PYTHONPATH=src python -m mobiphysio.cli run-all --skip-preprocess --resume"
    md = [f"# Run status — generated {now}", "",
          "Generated by `scripts/backup_status.py` from `experiments/full_v2/registry.json`, every run_manifest.json "
          "and the process logs. Status values come from the manifests; 'running' runs are cross-checked against live "
          "processes.", "", "## Active processes", ""]
    md += [f"- `{a.strip()}`" for a in active] or ["- none"]
    md += ["", "## Planned matrix (experiment `full_v2`)", "", "| Model | Seed | Status | Note |", "|---|---:|---|---|"]
    for p in planned:
        md.append(f"| {p['model']} | {p['seed']} | {p['status']} | {'historical (outside final scope)' if p['historical'] else ''} |")
    md += ["", "## All run directories", "",
           "| Run ID | Model | Seed | Status | Last epoch (logs) | Best epoch | Test macro F1 | Checkpoint SHA-256 (12) |",
           "|---|---|---:|---|---:|---:|---:|---|"]
    for r in rows:
        f1 = f"{r['macro_f1']:.4f}" if r.get("macro_f1") is not None else ""
        md.append(f"| `{r['run_id']}` | {r['model']} | {r['seed']} | {r['status']} | {r['last_epoch_in_logs'] or ''} | "
                  f"{r['best_epoch'] or ''} | {f1} | {(r['checkpoint_sha256'] or '')[:12]} |")
    md += ["", "## Resume", "", f"```bash\n{resume}\n```", "",
           "`--resume` skips every (model, seed) already registered as completed and marks run directories left in "
           "'running' state by a dead process as 'interrupted'. **Granularity is one whole run:** checkpoints are "
           "written only when a run finishes, so a run that was in progress restarts from epoch 1 (same seed, split "
           "and configuration). Optimizer/scheduler/RNG state of an unfinished run is not saved.",
           "", "Per-run log excerpts: `logs/experiments/<run_id>/log_excerpt.log`; full process logs: `logs/process_logs/`."]
    (ROOT / "reports" / "run_status.md").write_text("\n".join(md) + "\n")
    print(json.dumps({"active": active, "pending": [p for p in planned if p["status"] != "completed"]}, indent=1))


if __name__ == "__main__":
    main()
